const dictionaries: Record<AdminLocale, Record<AdminMessageKey, string>> = {
  "pt-BR": ptBR,
  "en-US": enUS,
}

export function detectAdminLocale(): AdminLocale {
  try {
    const stored = localStorage.getItem("hive_locale")
    if (stored === "pt-BR" || stored === "en-US") return stored
  } catch {
    /* sem storage: usa default */
  }
  if (typeof document !== "undefined" && document.documentElement.lang.toLowerCase().startsWith("en")) {
    return "en-US"
  }
  return "pt-BR"
}

export interface AdminI18n {
  locale: AdminLocale
  t: (key: AdminMessageKey, params?: Record<string, string | number>) => string
}

/** Hook com `t` estável — usar em callbacks e efeitos sem provocar loops. */
export function useAdminI18n(): AdminI18n {
  const [locale] = useState<AdminLocale>(detectAdminLocale)
  const t = useCallback<AdminI18n["t"]>(
    (key, params) => {
      const template = dictionaries[locale][key] ?? ptBR[key] ?? key
      if (!params) return template
      return template.replace(/\{(\w+)\}/g, (match, name: string) =>
        name in params ? String(params[name]) : match
      )
    },
    [locale]
  )
  return { locale, t }
}
